"""Template for the kgbridge worker cell (generated & pushed by `kg.py bridge start`).

Placeholders (@REPO@, @KEY@, @IDLE_MAX@, @EXTRA@) are substituted by kg.py.
@EXTRA@ stays empty in production; in selftest mode it injects the fake
transport shim and a stubbed secrets login.
"""

WORKER_TEMPLATE = '''# kgbridge worker v1 — auto-generated by scripts/kg.py (do not edit by hand)
import base64, json, os, sys, threading, time, traceback
from io import StringIO
@EXTRA@
from huggingface_hub import HfApi

REPO = "@REPO@"
KEY = "@KEY@"
IDLE_MAX_S = @IDLE_MAX@
POLL_S = 5.0

_req_dir = f"req/{KEY}"
_res_dir = f"res/{KEY}"
_hb_path = f"state/{KEY}/heartbeat.json"
_stop_path = f"state/{KEY}/stop.flag"

def _make_api():
    return HfApi()

def _resolve(p):
    return f"https://huggingface.co/datasets/{REPO}/resolve/main/{p}"

_api = _make_api()

def _up(path, obj):
    _api.upload_file(path_or_fileobj=json.dumps(obj).encode(),
                     path_in_repo=path, repo_id=REPO, repo_type="dataset")

def _dl(path):
    if os.environ.get("KGBRIDGE_FAKE_HF") == "1":
        import kgbridge_fake as _fake
        return _fake.dl(path)
    import requests
    headers = {"Authorization": f"Bearer {_api.token}"} if getattr(_api, "token", None) else {}
    r = requests.get(_resolve(path), headers=headers, timeout=60)
    if r.status_code == 404:
        return None
    r.raise_for_status()
    return r.content

def _stop_requested():
    try:
        return _dl(_stop_path) is not None
    except Exception:
        return False

def _hb():
    while True:
        try:
            _up(_hb_path, {"ts": time.time()})
        except Exception as e:
            print("[kgbridge] heartbeat upload failed:", e)
        time.sleep(20)

threading.Thread(target=_hb, daemon=True).start()

from IPython.core.displayhook import CapturingDisplayHook
from IPython.core.displaypub import CapturingDisplayPublisher
from IPython.core.getipython import get_ipython

class _CapDH(CapturingDisplayHook):
    is_active = False  # IPython 9 history machinery probes this

class _CapPub(CapturingDisplayPublisher):
    is_publishing = False
_shell = get_ipython()
assert _shell is not None, "kgbridge worker must run inside a notebook kernel"

print(f"[kgbridge] worker online  repo={REPO}  key={KEY[:6]}...  idle_max={IDLE_MAX_S}s")

_processed = set()
_idle = 0.0
while True:
    try:
        names = sorted(p for p in _api.list_repo_files(repo_id=REPO, repo_type="dataset")
                       if p.startswith(_req_dir + "/") and p.endswith(".json"))
    except Exception as e:
        print("[kgbridge] queue listing failed:", e)
        time.sleep(POLL_S)
        continue
    todo = [p for p in names if p.rsplit("/", 1)[-1] not in _processed]
    if not todo:
        _idle += POLL_S
        if _stop_requested():
            print("[kgbridge] stop flag received -> worker exiting")
            break
        if _idle >= IDLE_MAX_S:
            print(f"[kgbridge] idle for {IDLE_MAX_S}s -> worker exiting (session completes)")
            break
        time.sleep(POLL_S)
        continue
    _idle = 0.0
    for path in todo:
        seq = path.rsplit("/", 1)[-1][:-5]
        raw = _dl(path)
        if raw is None:
            _processed.add(seq)
            continue
        try:
            req = json.loads(raw)
        except Exception as e:
            print("[kgbridge] bad request:", e)
            _processed.add(seq)
            continue
        if req.get("key") != KEY:
            continue
        code = req.get("code", "")
        try:
            # Manual capture context: streams + display_pub + displayhook all wired
            # to one list. (capture_output alone misses execute_result because
            # DisplayTrap re-installs the shell's own hook for 'single'-mode cells.)
            _outs = []
            _old_stdout, _old_stderr = sys.stdout, sys.stderr
            _sout, _serr = StringIO(), StringIO()
            sys.stdout, sys.stderr = _sout, _serr
            _trap = _shell.display_trap
            _old_trap_hook = _trap.hook
            _old_pub = _shell.display_pub
            _old_shell_dh = _shell.displayhook
            _old_sys_dh = sys.displayhook
            _pub = _CapPub()
            _pub.outputs = _outs
            _cap_dh = _CapDH(shell=_shell, outputs=_outs)
            _shell.display_pub = _pub
            _shell.displayhook = _cap_dh
            _trap.hook = _cap_dh
            sys.displayhook = _cap_dh
            try:
                _result = _shell.run_cell(code, store_history=False)
            finally:
                _trap.hook = _old_trap_hook
                _shell.display_pub = _old_pub
                _shell.displayhook = _old_shell_dh
                sys.displayhook = _old_sys_dh
                _stdout_txt, _stderr_txt = _sout.getvalue(), _serr.getvalue()
                sys.stdout, sys.stderr = _old_stdout, _old_stderr
            outs = []
            for _o in _outs:
                _item = {}
                for _mime, _val in (_o.get("data") or {}).items():
                    if isinstance(_val, bytes):
                        _item[_mime] = {"b64": base64.b64encode(_val).decode()}
                    else:
                        _item[_mime] = str(_val)
                if _item:
                    outs.append(_item)
            if _result.success:
                payload = {"v": 1, "status": "ok", "outs": outs,
                           "stdout": _stdout_txt or "", "stderr": _stderr_txt or ""}
            else:
                _err = _result.error_in_exec or _result.error_before_exec
                if _err is not None:
                    _tb = traceback.format_exception(type(_err), _err, _err.__traceback__)
                else:
                    _tb = ["unknown error"]
                payload = {"v": 1, "status": "error", "outs": outs,
                           "stdout": _stdout_txt or "", "stderr": _stderr_txt or "",
                           "ename": type(_err).__name__ if _err else "Error",
                           "evalue": str(_err), "traceback": _tb}
        except Exception as e:
            payload = {"v": 1, "status": "error", "ename": "WorkerError", "evalue": str(e),
                       "traceback": traceback.format_exc().splitlines(),
                       "outs": [], "stdout": "", "stderr": ""}
        try:
            _up(f"{_res_dir}/{seq}.json", payload)
            _api.delete_file(path, repo_id=REPO, repo_type="dataset")
        except Exception as e:
            print("[kgbridge] reply upload failed:", e)
        _processed.add(seq)
        time.sleep(1.0)

print("[kgbridge] worker loop ended")
'''
